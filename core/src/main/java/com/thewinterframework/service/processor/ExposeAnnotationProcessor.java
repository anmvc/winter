package com.thewinterframework.service.processor;

import com.google.auto.service.AutoService;
import com.thewinterframework.processor.context.ProcessorContext;
import com.thewinterframework.processor.handler.WinterAnnotationProcessor;
import com.thewinterframework.processor.template.TemplateBuilder;
import com.thewinterframework.service.annotation.expose.Expose;
import org.jetbrains.annotations.Nullable;

import javax.lang.model.element.Element;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import java.lang.annotation.Annotation;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Set;
import java.util.regex.Pattern;

import static javax.lang.model.util.ElementFilter.methodsIn;

/**
 * Generates the implementation of the {@code <PLUGIN>API} interface declared/generated by
 * {@link ExposeAnnotationProcessorAPI} and the module that publishes it.
 * <p>
 * The API interface is the source of truth: every method declared in it is implemented by
 * delegating to the injector, using the method name and the return type of the interface.
 * This is what makes a hand written API interface (or an interface generated in another
 * compilation unit) work as expected.
 */
@AutoService(WinterAnnotationProcessor.class)
public class ExposeAnnotationProcessor implements WinterAnnotationProcessor {

	public static final Pattern ELEMENT_PATTERN = Pattern.compile("(?:<el>)([\\s\\S]*?)(?:<\\/el>)");

	/**
	 * Name of the generated module that publishes the API implementation.
	 */
	public static final String MODULE_NAME = "ExposeAPIModule";

	@Override
	public Set<Class<? extends Annotation>> getSupportedAnnotations() {
		return Set.of(Expose.class);
	}

	@Override
	public void onRoundStart(final ProcessorContext ctx) {
		if (!ctx.getRoundEnv().processingOver()) {
			return;
		}

		final var pkg = ctx.getPluginPackageString();
		final var pluginName = ctx.getPluginClass().getSimpleName().toString();
		final var apiElement = ctx.getEnv().getElementUtils().getTypeElement(pkg + "." + pluginName + "API");
		if (apiElement == null) {
			// There is no API interface for this plugin, so there is nothing to expose.
			return;
		}

		final var methods = exposedMethods(apiElement, ctx);
		if (methods == null || methods.isEmpty()) {
			// Nothing is exposed (or the API declares a type that cannot be exposed): do not wire a module that
			// would not be generated.
			return;
		}

		ctx.wireModule(pkg + "." + MODULE_NAME);
		generateFile(ctx, "generated/ExposeImplementationTemplate.java", "Default", methods);

		TemplateBuilder.fromResource("generated/ExposeModuleTemplate.java")
				.placeholder("PACKAGE", pkg)
				.placeholder("PLUGIN", pluginName)
				.write(ctx, pkg + "." + MODULE_NAME);
	}

	/**
	 * Collects the methods of the API interface that must be implemented.
	 *
	 * @param apiElement the API interface
	 * @param ctx        the processor context
	 * @return the methods of the API interface, sorted by name so the generated source is deterministic, or
	 * {@code null} when the API declares a method that cannot be exposed (an error is reported for it)
	 */
	private @Nullable List<ExposedMethod> exposedMethods(final TypeElement apiElement, final ProcessorContext ctx) {
		final var methods = new ArrayList<ExposedMethod>();

		for (final var method : methodsIn(apiElement.getEnclosedElements())) {
			if (!isAbstractInstanceMethod(method)) {
				continue;
			}

			// void and primitive return types cannot be resolved through the injector, the generated
			// implementation would not compile, so the error is reported on the offending method instead.
			final var returnElement = ctx.getEnv().getTypeUtils().asElement(method.getReturnType());
			if (!(returnElement instanceof final TypeElement typeElement)) {
				ctx.messager().printError(
						"The exposed method " + method.getSimpleName() + " of " + apiElement.getQualifiedName()
								+ " must return a declared type",
						method
				);
				return null;
			}

			methods.add(new ExposedMethod(method.getSimpleName().toString(), typeElement));
		}

		methods.sort(Comparator.comparing(ExposedMethod::name));
		return methods;
	}

	private static boolean isAbstractInstanceMethod(final ExecutableElement method) {
		final var modifiers = method.getModifiers();
		return !modifiers.contains(Modifier.STATIC)
				&& !modifiers.contains(Modifier.DEFAULT)
				&& !modifiers.contains(Modifier.PRIVATE);
	}

	@Override
	public void handle(final TypeElement annotation, final Set<? extends Element> elements, final ProcessorContext ctx) {
		// The exposed types are discovered through the generated API interface, see onRoundStart.
	}

	@SuppressWarnings("DuplicatedCode")
	public static void generateFile(final ProcessorContext ctx, final String templatePath, final String prefix, final Iterable<ExposedMethod> methods) {
		final var pkg = ctx.getPluginPackageString();
		final var pluginName = ctx.getPluginClass().getSimpleName().toString();
		TemplateBuilder.fromResource(templatePath)
				.placeholder("PACKAGE", pkg)
				.placeholder("PLUGIN", pluginName)
				.custom(content -> {
					final var matcher = ELEMENT_PATTERN.matcher(content);
					final var result = new StringBuilder();
					int lastEnd = 0;

					while (matcher.find()) {
						result.append(content, lastEnd, matcher.start());
						final var block = matcher.group(1);
						final var builder = new StringBuilder();

						for (final var method : methods) {
							builder.append(block
									.replace("<TYPE>", method.returnType().getQualifiedName())
									.replace("<METHOD_NAME>", method.name())
							).append(System.lineSeparator());
						}
						result.append(builder);
						lastEnd = matcher.end();
					}
					result.append(content.substring(lastEnd));
					return result.toString();
				})
				.write(ctx, pkg + "." + prefix + pluginName + "API");
	}

	public record ExposedMethod(String name, TypeElement returnType) {
	}
}
